"""Writes reports/EVALUATION.md and the routing figure from an evaluation result."""

from __future__ import annotations

from pathlib import Path


def _pct(v: float) -> str:
    return f"{v * 100:.1f}%"


def figure(res: dict, out: Path) -> str | None:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return None
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2), sharey=False)
    for ax, quality in zip(axes, ("standard", "high"), strict=True):
        data = res["routing"]["targets"][quality]
        for p in data["policies"]:
            marker = {
                "frontier-large": "s",
                "cheapest": "v",
                "point-estimate": "x",
                "lower-bound": "o",
                "lower-bound+cascade": "D",
            }[p["policy"]]
            ax.scatter(
                p["cost_per_1k_requests_eur"],
                p["quality"],
                marker=marker,
                s=70,
                label=p["policy"],
                color="#1f4e79" if "lower" in p["policy"] else "#9aa5b1",
            )
        ax.axhline(data["target"], color="#c0392b", lw=1, ls="--")
        ax.text(0.05, data["target"] + 0.004, f"target {data['target']:.0%}", color="#c0392b", fontsize=9)
        ax.set_xscale("log")
        ax.set_xlabel("cost per 1,000 requests (EUR, log scale)")
        ax.set_title(f"quality target: {quality}")
        ax.grid(alpha=0.25)
    axes[0].set_ylabel("share of answers that pass the grader")
    axes[1].legend(fontsize=8, loc="lower right")
    fig.suptitle(
        "Routing policies on 6,000 test requests (simulated models with hidden pass rates)", fontsize=11
    )
    fig.tight_layout()
    (out / "figures").mkdir(parents=True, exist_ok=True)
    path = out / "figures" / "routing.png"
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return "figures/routing.png"


def write(res: dict, out: Path) -> None:
    img = figure(res, out)
    r = res["routing"]
    lines = [
        "# Evaluation",
        "",
        f"Generated by `mrp evaluate` ({'quick' if res['meta']['quick'] else 'full'} run, {res['meta']['seconds']} s).",
        "",
    ]
    lines += ["## Routing: cost against quality", ""]
    if img:
        lines += [f"![routing]({img})", ""]
    lines += [
        f"Calibration: {r['calibration_items_per_cell']} items per task and model; test: {r['test_requests']} new requests. "
        "Models are simulated with hidden true pass rates; the router sees only calibration results.",
        "",
    ]
    for quality, data in r["targets"].items():
        lines += [
            f"### Target `{quality}` ({data['target']:.0%})",
            "",
            "| Policy | Quality | Tasks clearly below target | Cost / 1k requests | Saving vs frontier | p95 latency | Escalations |",
            "|---|---|---|---|---|---|---|",
        ]
        for p in data["policies"]:
            lines.append(
                f"| {p['policy']} | {_pct(p['quality'])} | {', '.join(p['tasks_clearly_below_target']) or 'none'} | €{p['cost_per_1k_requests_eur']:.3f} | "
                f"{_pct(p.get('saving_vs_frontier', 0))} | {p['p95_latency_ms']:.0f} ms | {_pct(p['escalation_rate'])} |"
            )
        lines.append("")
    sc = r["small_calibration"]
    lines += [
        f"### Only {sc['items_per_cell']} calibration items per cell (target {sc['target']:.0%})",
        "",
        "| Policy | Quality | Tasks clearly below target |",
        "|---|---|---|",
    ]
    for p in sc["policies"]:
        lines.append(
            f"| {p['policy']} | {_pct(p['quality'])} | {', '.join(p['tasks_clearly_below_target']) or 'none'} |"
        )
    d = r["drift"]
    lines += [
        "",
        f"### Drift: the cheap extraction model degrades after {d['degrades_after']:,} of {d['requests']:,} requests",
        "",
        "| | Quality per 500 requests |",
        "|---|---|",
        f"| without the health monitor | {' · '.join(_pct(x) for x in d['without_monitor']['quality_per_500_requests'])} |",
        f"| with the health monitor | {' · '.join(_pct(x) for x in d['with_monitor']['quality_per_500_requests'])} |",
        "",
        f"Taken out of rotation: {', '.join('/'.join(x) for x in d['with_monitor']['excluded']) or 'nothing'}. "
        f"False exclusions over 6,000 healthy requests: {len(d['false_exclusions_in_steady_state'])}.",
        "",
    ]
    b = res["billing"]
    lv, cb, inv = b["ledger_vs_provider_records"], b["customer_billing"], b["invoice_reconciliation"]
    lines += [
        "## Billing under failure",
        "",
        f"{b['requests']:,} requests, {b['provider_calls']:,} provider calls. Injected: "
        + ", ".join(f"{k.replace('_', ' ')} {v}" for k, v in b["injected"].items())
        + ".",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| Provider charges missing from the ledger (after reconciliation) | {lv['charges_missing_from_ledger']} of {lv['provider_charges']:,} |",
        f"| Ledger costs that differ from the provider's | {lv['cost_mismatches']} |",
        f"| Costs in the ledger the provider never charged | {lv['ledger_costs_never_charged']} |",
        f"| Requests with more than one usage row | {cb['keys_with_more_than_one_row']} |",
        f"| Customer billed a wrong amount | {cb['billed_amount_wrong']} |",
        f"| Customer billed without getting an answer | {cb['billed_without_an_answer']} |",
        f"| Calls settled by the reconciler | {b['reconciler']['settled']} of {b['reconciler']['checked']} |",
        f"| Planted invoice errors found ({inv['planted']}) | {'all' if inv['all_found'] else 'NOT all'} |",
        "",
        f"Actual spend €{cb['actual_spend_eur']}, billed €{cb['billed_eur']} (plan markups; failed calls are our cost).",
        "",
        "## Semantic cache",
        "",
        f"{res['cache']['pairs']} pairs of repeats (same question, different form) and near misses (one amount, country, product, date or negation changed). Embedder: {res['cache']['embedder']}.",
        "",
        "| Threshold | Repeats served | Near misses served | Repeats served, slot check | Near misses served, slot check |",
        "|---|---|---|---|---|",
    ]
    for x in res["cache"]["by_threshold"]:
        lines.append(
            f"| {x['threshold']:.2f} | {_pct(x['repeats_served'])} | {_pct(x['near_misses_served'])} | {_pct(x['repeats_served_with_slot_check'])} | {_pct(x['near_misses_served_with_slot_check'])} |"
        )
    ld = res["load"]
    lines += [
        "",
        "## Gateway overhead",
        "",
        "| Concurrency | Requests/s | p50 | p95 | p99 | Errors |",
        "|---|---|---|---|---|---|",
    ]
    for k in ("concurrency_1", "concurrency_16"):
        x = ld[k]
        lines.append(
            f"| {k.split('_')[1]} | {x['requests_per_second']} | {x['p50_ms']} ms | {x['p95_ms']} ms | {x['p99_ms']} ms | {x['errors']} |"
        )
    lines += ["", ld["note"] + ".", "", "## Objectives (`mrp gate`)", "", "| Measure | Value |", "|---|---|"]
    for k, v in res["measures"].items():
        lines.append(f"| {k} | {v} |")
    lines.append("")
    (out / "EVALUATION.md").write_text("\n".join(lines))
